#!/usr/bin/env bash
# container/gen-env.sh — freeze `module load lfric-env/<version>/spack` into a
# plain env file, for the image's activation hook. Run by the Containerfile's
# build stage, under `pixi run` in stage1/ (for MODULEFILES_DIR/MODULE_NAME/...).
#
# Why freeze: the modulefile is the contract (stage1/lfric-env.lua), but inside
# the container activation has to work where Lmod cannot run — Apptainer sources
# /.singularity.d/env/*.sh with its own built-in shell interpreter — and should
# not cost an Lmod run on every `apptainer exec` of every MPI rank. So the module
# is loaded ONCE here, in a clean environment, and what it set is written out as
# `export` lines. The Lmod state variables are kept, so `module list` inside the
# container still names lfric-env.
#
# Also writes the stable paths the host helper binds over to swap MPI libraries
# (container/README.md, "MPI"), the link the container's Cylc site config
# includes, and asserts the overlay's generic target held.
set -euo pipefail
die() { echo "ERROR: gen-env.sh: $*" >&2; exit 1; }

out_dir=/opt/lfric-env/container
mkdir -p "$out_dir/etc" "$out_dir/lib/swap"

# --- 1. Generic target: every spec in the lock is target=aarch64 -----------
python3 - "$SPACK_ENV_DIR/spack.lock" <<'EOF' || die "the environment is not all target=aarch64"
import collections, json, sys
specs = json.load(open(sys.argv[1]))["concrete_specs"].values()
t = collections.Counter(
    s["arch"]["target"] if isinstance(s["arch"]["target"], str) else s["arch"]["target"]["name"]
    for s in specs)
print("INFO: targets in the lock:", dict(t))
sys.exit(0 if set(t) == {"aarch64"} else 1)
EOF

# --- 2. The frozen module environment -------------------------------------
# A clean shell with only the image's own PATH, so nothing from the build
# (pixi, Spack, this script's environment) leaks into the result.
base_path=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin
env -i HOME=/root PATH="$base_path" MODULEFILES_DIR="$MODULEFILES_DIR" MODULE_NAME="$MODULE_NAME" \
  bash --norc --noprofile -c '
    . /usr/share/lmod/lmod/init/bash
    env -0 > /tmp/env.before
    module use "$MODULEFILES_DIR"
    module load "$MODULE_NAME" || exit 1
    env -0 > /tmp/env.after' \
  || die "module load $MODULE_NAME failed in a clean shell"

python3 - /tmp/env.before /tmp/env.after "$out_dir/env.sh" "$MODULE_NAME" <<'EOF'
import sys
def load(p):
    return dict(kv.split("=", 1) for kv in open(p).read().split("\0") if "=" in kv)
before, after = load(sys.argv[1]), load(sys.argv[2])
# Shell bookkeeping, and the exported shell functions Lmod defines: not state.
skip = {"PWD", "OLDPWD", "SHLVL", "_", "MODULEFILES_DIR", "MODULE_NAME"}
# Lmod's own state is written out whether or not the load changed it: activate.sh
# drops the HOST's Lmod variables, and these are what replace them.
lmod = ("LMOD", "__LMOD", "_ModuleTable", "MODULE", "LOADEDMODULES", "_LMFILES_")
q = lambda s: "'" + s.replace("'", "'\\''") + "'"
with open(sys.argv[3], "w") as f:
    f.write("# Generated by container/gen-env.sh at image build time. Do not edit.\n")
    f.write(f"# What `module load {sys.argv[4]}` sets, frozen; sourced by activate.sh.\n")
    for k in sorted(after):
        if k in skip or k.startswith("BASH_FUNC_"):
            continue
        if before.get(k) == after[k] and not k.startswith(lmod):
            continue
        f.write(f"export {k}={q(after[k])}\n")
EOF
grep -q '^export FC=' "$out_dir/env.sh" || die "the frozen environment has no FC"
grep -q '^export LFRIC_ENV_MODULE=' "$out_dir/env.sh" || die "the frozen environment has no LFRIC_ENV_MODULE"
echo "INFO: wrote $out_dir/env.sh ($(wc -l < "$out_dir/env.sh") lines)"

# --- 3. Stable paths for the MPI library swap -----------------------------
# The real files sit under hash-addressed Spack prefixes, and the env's own
# libraries reach them through RPATH, which LD_LIBRARY_PATH cannot override. So
# the host helper swaps a library by bind-mounting the host's file over the
# container's — and needs a path that does not change between builds. These
# symlinks are that path (a bind onto a symlink lands on its target).
view="$SPACK_ENV_DIR/.spack-env/view"
{
  echo "# Generated by container/gen-env.sh. The libraries the host helper may swap."
  for lib in libmpi.so.12 libmpifort.so.12 libfabric.so.1; do
    real="$(readlink -f "$view/lib/$lib")" || die "no $lib in $view/lib"
    [ -f "$real" ] || die "$view/lib/$lib does not resolve to a file"
    ln -sfn "$real" "$out_dir/lib/swap/$lib"
    echo "# $lib -> $real"
  done
} > "$out_dir/etc/swap.txt"
cat "$out_dir/etc/swap.txt"

# --- 4. The module's Cylc site config, for the container's to include ------
mkdir -p "$out_dir/etc/cylc/flow"
ln -sfn "$LFRIC_PREFIX/etc/cylc/flow/global.cylc" "$out_dir/etc/cylc/flow/site.cylc"
[ -f "$out_dir/etc/cylc/flow/site.cylc" ] || die "no Cylc site config at $LFRIC_PREFIX/etc/cylc/flow/global.cylc"
